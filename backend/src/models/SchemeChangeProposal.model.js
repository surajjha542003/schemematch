/**
 * SCHEME FINDER — Scheme Change Proposal Model
 *
 * Every fetch that succeeds and structures cleanly lands here, always — see
 * runIngestion.js. A high-confidence read of an already-vetted SOURCES.js
 * URL also gets auto-applied straight into the live Scheme collection right
 * away (status here is stamped 'approved', reviewedBy an "auto-ingestion"
 * marker) — this collection still holds the full record either way, as an
 * audit trail. Anything less than high confidence stays 'pending' for a
 * human to approve/reject via the review endpoint.
 */

const mongoose = require('mongoose');

const SchemeChangeProposalSchema = new mongoose.Schema(
  {
    schemeId:      { type: String, required: true },
    // true when schemeId was generated by discovery (discoverListing.js)
    // for a scheme not already in the static datasets or DB — approving
    // this proposal creates a new Scheme doc instead of updating one.
    // Named isNewScheme, not isNew — `isNew` is a reserved Mongoose Document
    // property (unsaved-doc tracking) and collides with a schema field.
    isNewScheme:   { type: Boolean, default: false },
    sourceUrl:     { type: String, required: true },
    sourceType:    { type: String, enum: ['html', 'pdf'], required: true },
    fetchedAt:     { type: Date, required: true },
    fetchOk:       { type: Boolean, required: true },
    fetchError:    String,
    extracted:     mongoose.Schema.Types.Mixed, // structureViaLLM output
    extractionOk:  Boolean,
    extractionNote: String,
    status:        { type: String, enum: ['pending', 'reviewing', 'approved', 'rejected'], default: 'pending' },
    finalUrl:      String,
    sourceHash:    String,
    sourceExcerpt: String,
    textTruncated: Boolean,
    reviewNote:    String,
    reviewedBy:    String,
    reviewedAt:    Date,
  },
  { timestamps: true }
);

module.exports = mongoose.model('SchemeChangeProposal', SchemeChangeProposalSchema);
