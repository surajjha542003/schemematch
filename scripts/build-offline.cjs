const fs=require('node:fs'),path=require('node:path'),{createHash}=require('node:crypto');
const base=path.resolve(__dirname,'../frontend/src'),html=fs.readFileSync(path.join(base,'index.html'),'utf8');
const linked=[...html.matchAll(/(?:src|href)="((?:js|css)\/[^"?]+)(?:\?[^\"]*)?"/g)].map(m=>m[1]);
const assets=[...new Set(['index.html',...linked,'data/state-scholarships.json','data/central-scholarships.json','data/other-schemes.json','data/exam-calendar.json'])];
const hash=createHash('sha256');for(const file of assets){hash.update(file);hash.update(fs.readFileSync(path.join(base,file)));}
const version=hash.digest('hex').slice(0,20);
const code=`/* GENERATED by scripts/build-offline.cjs after public frontend edits. */
const CACHE='schemematch-public-${version}';
const ASSETS=${JSON.stringify(assets)};
const paths=new Set(ASSETS.map(file=>new URL(file,self.registration.scope).pathname));
self.addEventListener('install',event=>{event.waitUntil((async()=>{const cache=await caches.open(CACHE);await cache.addAll(ASSETS.map(file=>new Request(new URL(file,self.registration.scope),{cache:'reload'})));await self.skipWaiting();})());});
self.addEventListener('activate',event=>{event.waitUntil((async()=>{for(const name of await caches.keys())if(name.startsWith('schemematch-public-') && name!==CACHE)await caches.delete(name);await self.clients.claim();})());});
self.addEventListener('fetch',event=>{
  const request=event.request,url=new URL(request.url);
  if(request.method!=='GET' || url.origin!==self.location.origin || url.pathname.startsWith('/api/') || url.pathname==='/health')return;
  if(request.mode==='navigate'){
    event.respondWith((async()=>{try{const response=await fetch(request);if(response.ok)return response;}catch(_){}return (await caches.open(CACHE)).match(new URL('index.html',self.registration.scope));})());return;
  }
  if(!paths.has(url.pathname))return;
  event.respondWith((async()=>{const cache=await caches.open(CACHE);return (await cache.match(request,{ignoreSearch:true})) || fetch(request);})());
});
`;
const target=path.join(base,'sw.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==code)throw new Error('Rebuild public offline shell: npm run offline:build');}else fs.writeFileSync(target,code);
console.log('Validated '+assets.length+' public offline assets.');
