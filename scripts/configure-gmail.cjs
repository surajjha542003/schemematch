// Run in your own Terminal; password input is hidden and never printed.
const fs=require('node:fs'),path=require('node:path');
const {hiddenQuestion}=require('./configure-mongodb.cjs');
const {smtpConfig}=require('../backend/src/services/proposalEmail.service');
const dotenv=require('../backend/node_modules/dotenv'),nodemailer=require('../backend/node_modules/nodemailer');
const root=path.resolve(__dirname,'..');
async function main(){
 if(!process.stdin.isTTY)throw new Error('Run npm run mail:configure in your own interactive Terminal.');
 const previous=dotenv.parse(fs.readFileSync(path.join(root,'backend/.env')));
 const email=(await hiddenQuestion('Gmail sender address (hidden; Enter keeps current address): ')).trim() || previous.SMTP_USER;
 const password=(await hiddenQuestion('Google-generated 16-character App Password (hidden): ')).replace(/\s/g,'');
 if(!/^[A-Za-z0-9]{16}$/.test(password))throw new Error('Use the 16-character password generated by Google App Passwords. Files unchanged.');
 const values={SMTP_HOST:'smtp.gmail.com',SMTP_PORT:'465',SMTP_SECURE:'true',SMTP_USER:email,SMTP_FROM:email,SMTP_PASS:password};
 const config=smtpConfig(values);if(!config)throw new Error('Enter a valid Gmail sender address. Files unchanged.');
 console.log('Verifying Gmail connection and authentication…');
 const transport=nodemailer.createTransport(config.transport);
 try{await transport.verify();}catch(_){throw new Error('Gmail authentication failed. Check that this App Password belongs to the sender address. Files unchanged.');}finally{transport.close();}
 const files=['.env','backend/.env'].map(file=>path.join(root,file));
 const originals=files.map(file=>fs.existsSync(file)?fs.readFileSync(file,'utf8'):'');
 const updates=originals.map(original=>{
  let text=original;for(const [key,value] of Object.entries(values)){
   // Remove duplicate definitions; preserve all unrelated environment settings.
   const pattern=new RegExp('^\\s*'+key+'\\s*=.*$','gm');text=text.replace(pattern,'');
   text=text.replace(/\s*$/,'')+'\n'+key+'='+JSON.stringify(value)+'\n';
  }return text;
 });
 try{files.forEach((file,i)=>{fs.writeFileSync(file,updates[i],{mode:0o600});fs.chmodSync(file,0o600);});}
 catch(_){files.forEach((file,i)=>{fs.writeFileSync(file,originals[i],{mode:0o600});});throw new Error('Could not update environment files; original settings restored.');}
 console.log('Gmail verified. Both private environment files updated. No email sent and no password displayed.');
 console.log('Tell Codex this succeeded so it can configure the Vercel backend.');
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
