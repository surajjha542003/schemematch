const fs=require('node:fs');
const path=require('node:path');
const {createHash}=require('node:crypto');
const base=path.resolve(__dirname,'../frontend/src');
const records=JSON.parse(fs.readFileSync(path.join(base,'data/exam-calendar.json'),'utf8'));
const trustedAcademicHosts=['gate2027.iitm.ac.in','tancet.annauniv.edu','cetcell.mahacet.org','astu.ac.in','pgecetadm.tgche.ac.in','edcetadm.tgche.ac.in','pecetadm.tgche.ac.in'];
function officialUrl(value){
  try{const u=new URL(value);return u.protocol==='https:' && !u.username && !u.password && !u.port && (/\.(gov|nic)\.in$/.test(u.hostname) || trustedAcademicHosts.includes(u.hostname)) ? u.href : null;}catch(_){return null;}
}
function validDate(value){return /^\d{4}-\d{2}-\d{2}$/.test(value) && new Date(value+'T00:00:00Z').toISOString().slice(0,10)===value;}
const ids=new Set();
for(const e of records){
  if(ids.has(e.id) || !/^[a-z0-9-]+$/.test(e.id))throw new Error('Duplicate/invalid exam ID');ids.add(e.id);
  if(!officialUrl(e.source) || !e.name || !e.by || !e.sourceChecked || !['admission','recruitment'].includes(e.kind))throw new Error('Incomplete official exam reference: '+e.id);
  if(!Array.isArray(e.examDates) || e.examDates.some(d=>!validDate(d)) || (!e.datesVerified && e.examDates.length))throw new Error('Unverified exam date: '+e.id);
  if(e.datesVerified && !e.examDates.length)throw new Error('Missing verified schedule: '+e.id);
  if(e.registrationDeadline && (!e.registrationDeadlineVerified || !validDate(e.registrationDeadline)))throw new Error('Unverified registration deadline: '+e.id);
}
const code=`/* GENERATED by scripts/build-exams.cjs. Edit data/exam-calendar.json. */
(function(root,factory){const api=factory();if(typeof module==='object' && module.exports)module.exports=api;else root.ExamCalendar=api;})(typeof globalThis!=='undefined'?globalThis:this,function(){
  const records=${JSON.stringify(records,null,2)};
  const version='${createHash('sha256').update(JSON.stringify(records)).digest('hex')}';
  const trustedAcademicHosts=${JSON.stringify(trustedAcademicHosts)};
  ${officialUrl.toString()}
  function today(now=new Date()){return new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Kolkata',year:'numeric',month:'2-digit',day:'2-digit'}).format(now);}
  function schedule(e,date=today()){
    if(!e.datesVerified || !e.examDates.length)return {status:'unconfirmed',date:null,days:null};
    const future=e.examDates.filter(d=>d>=date).sort();
    const next=future[0] || [...e.examDates].sort().at(-1);
    return {status:future.length?'upcoming':'past',date:next,days:Math.round((Date.parse(next+'T00:00:00Z')-Date.parse(date+'T00:00:00Z'))/86400000)};
  }
  function filter({state='all',kind='all',status='current',query='',date=today()}={}){
    const q=query.trim().toLowerCase();
    return records.filter(e=>(state==='all' || (state==='central'?!e.state:e.state===state)) && (kind==='all' || e.kind===kind) && (!q || [e.name,e.by,e.state || 'Central',...(e.tags || [])].join(' ').toLowerCase().includes(q)) && (status==='all' || (status==='current'?schedule(e,date).status!=='past':schedule(e,date).status===status))).sort((a,b)=>(schedule(a,date).date || '9999').localeCompare(schedule(b,date).date || '9999') || a.name.localeCompare(b.name));
  }
  function registrationDeadlines({state,date=today()}={}){
    return records.filter(e=>e.registrationDeadlineVerified && e.registrationDeadline>=date && (!e.state || !state || e.state===state)).sort((a,b)=>a.registrationDeadline.localeCompare(b.registrationDeadline) || a.name.localeCompare(b.name));
  }
  return {records,version,officialUrl,today,schedule,filter,registrationDeadlines};
});
`;
const target=path.join(base,'js/exam-calendar.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==code)throw new Error('Rebuild exam calendar: npm run exams:build');}else fs.writeFileSync(target,code);
console.log('Validated '+records.length+' official exam references.');
