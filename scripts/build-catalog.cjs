/* JSON files are the source of truth; commit the generated offline browser bundle. */
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const base = path.resolve(__dirname, '../frontend/src');
const records = ['state-scholarships', 'central-scholarships', 'other-schemes']
  .flatMap(file => JSON.parse(fs.readFileSync(path.join(base, 'data', file + '.json'), 'utf8')));
const policy = require(path.join(base, 'js/source-policy'));
const conditions = require(path.join(base, 'js/reviewed-conditions'));
const ids = new Set();
for (const s of records) {
  if (!/^[a-z0-9-]+$/.test(s.id)) throw new Error('Invalid stable programme id');
  if (ids.has(s.id)) throw new Error('Duplicate scheme id: ' + s.id);
  ids.add(s.id);
  if (!policy.officialUrl(s.source) || (s.applicationUrl && !policy.officialUrl(s.applicationUrl))) throw new Error('Unapproved source route: ' + s.id);
  if (!['form','registration','login','download','institution','closed','unavailable'].includes(s.applicationAccess)) throw new Error('Missing application access status: '+s.id);
  if (s.applicationUrl && policy.applicationUrl(s)!==s.applicationUrl) throw new Error('Homepage or disabled route cannot be an application: '+s.id);
  if (s.registrationUrl && !policy.officialUrl(s.registrationUrl)) throw new Error('Unapproved registration route: '+s.id);
  for(const link of s.applicationOptions || [])if(!link.label || !policy.officialUrl(link.url))throw new Error('Invalid application option: '+s.id);
  if (['form','registration','login','download'].includes(s.applicationAccess) && (!s.applicationChecked || !policy.officialUrl(s.applicationSource) || !policy.applicationActions(s).links.length)) throw new Error('Missing application-route evidence: '+s.id);
  if (['institution','closed','unavailable'].includes(s.applicationAccess) && (s.applicationUrl || s.registrationUrl || s.applicationOptions?.length || !s.applicationNote)) throw new Error('Unavailable application must not link to a homepage: '+s.id);
  if (s.amtNum !== 0) throw new Error('An applicant award must be calculated at runtime: ' + s.id);
  if (s.matchingEnabled !== false && s.matchingEnabled !== true) throw new Error('Missing review gate: '+s.id);
  if (s.matchingEnabled === true && !(s.reviewedConditions?.complete===true && s.reviewedConditions.checks?.length && s.benefitVerified && s.benefit && policy.officialUrl(s.reviewedConditions.source) && policy.officialUrl(s.benefit.source))) throw new Error('Reviewed matching contract missing: '+s.id);
  for(const check of s.reviewedConditions?.checks || []) if(!conditions.fields[check.field] || !['incomeMax','oneOf','minimum','maximum','route'].includes(check.op))throw new Error('Invalid reviewed check: '+s.id);
  for(const doc of s.documentChecklist || [])if(!doc.id || !doc.label || !policy.officialUrl(doc.source))throw new Error('Invalid document evidence: '+s.id);
}
const code = `/* GENERATED by scripts/build-catalog.cjs. Edit data/*.json, then rebuild. */
(function(root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.SchemeCatalog = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function() {
  const version = '${createHash('sha256').update(JSON.stringify(records)).digest('hex')}';
  const records = ${JSON.stringify(records, null, 2)};
  function stateOf(s) { return s.state || null; }
  function relevant(s, profile) {
    const state = profile?.eligibilityDetails?.domicileState || profile?.state;
    return !stateOf(s) || (!!state && stateOf(s) === state);
  }
  function audienceRelevant(s, profile) {
    const a=s.audience;
    const state=profile?.eligibilityDetails?.domicileState || profile?.state;
    return !a || ((!a.domicileStates || !state || a.domicileStates.includes(state)) && [['education','edu'],['categories','cat'],['genders','gender']].every(([key,field]) => !a[key] || !profile?.[field] || a[key].includes(profile[field])));
  }
  function forProfile(profile, sector = 'students') {
    return balanced(records.filter(s => relevant(s, profile) && audienceRelevant(s, profile) && (sector === 'all' || (s.sector || 'students') === sector)));
  }
  function balanced(items) {
    const groups = new Map();
    items.forEach(s => { const k = stateOf(s) || 'Central'; if (!groups.has(k)) groups.set(k, []); groups.get(k).push(s); });
    const result = [];
    for (let i = 0; ; i++) { let added = false; for (const group of groups.values()) if (group[i]) { result.push(group[i]); added = true; } if (!added) break; }
    return result;
  }
  return { version, records, stateOf, relevant, audienceRelevant, forProfile, balanced };
});
`;
const target = path.join(base, 'js/scheme-catalog.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== code) throw new Error('Rebuild catalogue: npm run catalog:build');
} else fs.writeFileSync(target, code);
console.log('Validated ' + records.length + ' official-source listings.');
